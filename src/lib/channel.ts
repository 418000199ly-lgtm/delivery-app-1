// 渠道分流（2026-11-24 华为审核整改）：同一套代码出两个版本——
// - driver（司机版）：自家渠道分发，功能全开（支付宝购买/钱包充值/
//   自更新/锁屏亮屏提醒），CI 默认构建，未注入 VITE_CHANNEL 即此版；
// - store（商店版）：华为应用市场审核版，构建时注入 VITE_CHANNEL=store。
//   与司机版的差异全部由 IS_STORE_BUILD 门控：
//   1) 隐藏会员购买与钱包充值的支付发起入口（华为第 8 条：个人开发者
//      账号应用内不得含支付交易功能），购买/钱包页只留客服邮箱；
//   2) 关掉 App 内自更新（商店版走应用市场更新）；
//   3) 首次申请定位/通知权限前先弹用途说明（华为第 6 条）；
//   4) 返回键有响应（华为第 3 条）；隐私政策用商店版文案（第 4/5 条）。
//   锁屏覆盖（第 2 条）在原生层由 AndroidManifest 的 heiwan_channel
//   meta-data 门控，CI 商店版构建时改值 + 改 showWhenLocked 属性。
// 司机版行为零变化：所有门控在 driver 构建下均为假、走原路径。
// ============================================================

export const IS_STORE_BUILD: boolean = (() => {
  try {
    return String((import.meta as any).env?.VITE_CHANNEL || '') === 'store';
  } catch (_) {
    return false;
  }
})();

